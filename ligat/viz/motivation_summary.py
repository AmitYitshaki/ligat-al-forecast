"""Hebrew standalone summary and numbered findings, with every numeric token registered."""

from collections.abc import Mapping
from functools import partial
from html import escape

from ligat.analysis.motivation_summary import Claim, format_claim


def claim_span(claims: Mapping[str, Claim], key: str) -> str:
    """Render one checked claim; identifiers stay in HTML attributes, outside the visible text."""
    value = escape(format_claim(claims[key]))
    return f'<span data-claim="{escape(key)}"><bdi dir="ltr">{value}</bdi></span>'


def bottom_line(claims: Mapping[str, Claim]) -> str:
    """The same four reader-facing points in the opening and standalone conclusion."""
    c = partial(claim_span, claims)
    return f"""<section id="bottom-line" dir="rtl" style="line-height:1.8">
<h3>השורה התחתונה</h3><ul>
<li><b>השאלה:</b> האם לדעת כמה המשחק חשוב לכל קבוצה עוזר לחזות ניצחון, תיקו או הפסד,
מעבר לדירוג הכוח של הקבוצות (Elo)?</li>
<li><b>התשובה: לא.</b> בדקנו {c("configurations")} דרכים לשלב מוטיבציה בתחזית,
ואף אחת לא שיפרה אותה באופן יציב. בחמש העונות האחרונות ({c("recent_period")}) רובן אפילו
מקלקלות.</li>
<li><b>ההכרעה (עמית, <span class="reference">ה-כ23</span>):</b>
חיזוי ניצחון/תיקו/הפסד נשאר על סמך Elo בלבד.</li>
<li><b>מה ממשיך:</b> הדגל "אין על מה לשחק" ייבדק במודל השערים, במחברת {c("goals_book")}.
במשחקים של קבוצות כאלה יש יותר שערים מהצפוי.</li>
</ul></section>"""


