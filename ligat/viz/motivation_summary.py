        ("שלוש דרגות", "three", "הטובה ביותר בכל התקופה, אבל נכשלת בעונות האחרונות"),
        (
            "חשיבות לכל יעד",
            "components",
            "העקבית ביותר, והיחידה שמשפרת בממוצע בעונות האחרונות. כנראה מודדת כוח ולא מוטיבציה",
        ),
