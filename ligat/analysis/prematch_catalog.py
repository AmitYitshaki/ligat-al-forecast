CATALOG_NAMES = {
    "feature": "פיצ'ר",
    "words": "מה זה, במילים",
    "group": "קבוצה",
    "known": "מתי ידוע",
    **{model: model for model in ("M1", "M2", "M4", "M5")},
    "notes": "הערות",
    "explained_at": "איפה מוסבר",
}


def prematch_feature_overview(columns: Sequence[str] = PREMATCH_COLUMNS) -> pd.DataFrame:
    """Describe selected M0 columns without inferring or changing any model permission.

    Identification fields are documented but have no model status. Registered
    features use their model-specific override when present, and a dash for a
    model outside their declared roles. Unknown or duplicate columns fail closed.
    """
    if len(set(columns)) != len(columns) or set(columns) - EXPLANATIONS.keys():
        raise ValueError("Catalog requires unique, explicitly documented prematch columns")
    rows = []
    for column in columns:
        words, group, notes, explained_at = EXPLANATIONS[column]
        spec = FEATURES.get(column)
        if spec is None and column not in IDENTIFICATION_COLUMNS:
            raise ValueError(f"Unregistered catalog feature: {column}")
        known = spec.availability if spec else "K"
        row = dict(
            feature=column,
            words=words,
            group=group,
            known={"D": "לפני כל משחק", "S": "לפני העונה", "K": "ידוע מהלוח"}[known],
            notes=notes,
            explained_at=explained_at,
        )
        for model in ("M1", "M2", "M4", "M5"):
            row[model] = (
                dict(spec.model_status).get(model, spec.status)
                if spec and model in spec.models
                else "—"
            )
        rows.append(row)
    return pd.DataFrame(rows, columns=CATALOG_NAMES)
